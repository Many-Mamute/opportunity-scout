def detect_format(ev: Event) -> Optional[str]:
    hay = f"{ev.title} {ev.one_line_summary} {ev.organiser}".lower()
    for key, pattern in _FORMAT_PATTERNS:
        if re.search(pattern, hay):
            return key
    return ev.type if ev.type in FORMAT_NOTES else None


def skills_for(ev: Event) -> List[str]:
    out = list(SKILLS.get(ev.type, []))
    for f in ev.fields:
        out += FIELD_SKILLS.get(f, [])
    seen, uniq = set(), []
    for s in out:
        if s not in seen:
            seen.add(s)
            uniq.append(s)
    return uniq[:4]


def _cost_sentence(ev: Event, cfg: dict) -> Optional[str]:
    price = ev.price_eur()
    free_floor = cfg["cost"].get("never_exclude_below_eur", 50)
    if ev.cost == "funded":
        return ("It is funded, so the cost of going is your time rather than "
                "your money.")
    if ev.cost == "free" or price == 0:
        return None
    if price is None:
        return ("The price is not stated anywhere the scout could find — worth "
                "establishing before you invest any effort in applying.")
    if price <= free_floor:
        return (f"At €{price:g} it is cheap enough that the real cost is the "
                f"{ev.estimated_effort_hours}h, not the ticket.")
    basis = []
    if ev.rewards not in (NOT_STATED, "none stated", ""):
        basis.append(f"it comes with {ev.rewards.replace('_', ' ')}")
    if ev.selectivity in ("competitive", "invite_only"):
        basis.append("entry is selective, which is part of what the line is worth")
    if (ev.prestige_score or 0) >= 4:
        basis.append("the organiser is recognised")
    tail = ("; " + ", and ".join(basis)) if basis else \
           ("; nothing stated justifies that price, so treat it sceptically "
            "unless you can find out what you get")
    return f"It costs €{price:g}{tail}."


def _fit_sentence(ev: Event, cfg: dict) -> str:
    fw = cfg["scoring"]["field_weights"]
    best = max(ev.fields, key=lambda f: fw.get(f, 0.0), default=None)
    weight = fw.get(best, 0.0) if best else 0.0
    label = (best or "").replace("_", " ")
    if "your own faculty" in ev.flags:
        return ("It is run inside your own faculty, which makes it the "
                "cheapest thing on this list to attend and the easiest to "
                "follow up on afterwards.")
    if weight >= 0.85:
        return f"It sits squarely in {label}, one of your highest priorities."
    if weight >= 0.6:
        return f"It is adjacent to your core interests via {label}."
    if best:
        return (f"It is a stretch from your main areas — {label} — so it earns "
                f"its place on breadth rather than direct relevance.")
    return ("Nothing in it matched your stated interests, so it is here on "
            "general merit alone.")


def _timing_sentence(ev: Event, today: date) -> Optional[str]:
    d = ev.days_until_next_deadline
    if d is not None and d <= 7:
        return (f"The deadline is {d} day(s) away, so this is a decision for "
                f"this week rather than a bookmark.")
    if ev.calendar_conflict == "clashes_with_term_time":
        return (f"It falls in term time and costs about "
                f"{ev.estimated_effort_hours}h, so it comes out of study weeks.")
    if ev.calendar_conflict == "near_exams":
        return "It sits close to an exam period — check your own timetable first."
    if ev.intensity in ("heavy", "intense"):
        return (f"At roughly {ev.estimated_effort_hours}h it is a real "
                f"commitment, not an evening.")
    return None


def build_note(ev: Event, cfg: dict, today: date) -> List[str]:
    """Two to five sentences, in the order you would actually want them."""
    lines = []
    fmt = detect_format(ev)
    if fmt and fmt in FORMAT_NOTES:
        lines.append(FORMAT_NOTES[fmt])
    lines.append(_fit_sentence(ev, cfg))
    cost = _cost_sentence(ev, cfg)
    if cost:
        lines.append(cost)
    timing = _timing_sentence(ev, today)
    if timing:
        lines.append(timing)
    if ev.domestic_twin:
        lines.append(f"A Portuguese edition of this is also open "
                     f"({ev.domestic_twin}); compare the two before booking "
                     f"travel.")
    return lines


def annotate(ev: Event, cfg: dict, today: date) -> None:
    ev.analysis = build_note(ev, cfg, today)
    ev.skills_developed = skills_for(ev)
