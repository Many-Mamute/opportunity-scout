"""The short analysis printed under every event: why you might pursue this one,
what it will actually be like, and what you would come away able to do.

Deliberately NOT generated by a language model. Every sentence is composed from
facts the scout already holds — type, fields, cost, effort, selectivity, travel,
your own faculty, deadline pressure — plus a small hand-written knowledge base
describing what each FORMAT involves. That knowledge base describes the format
in general ("a Toastmasters club meets fortnightly and..."), never the specific
event, so there is nothing here that can be fabricated about a particular
opportunity. It is also free, deterministic, and testable.
"""
